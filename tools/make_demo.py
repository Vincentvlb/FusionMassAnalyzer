"""Regenerate palette/demo.js: demo payload used when the palette is opened
outside Fusion (plain browser preview). Built with the real mass_tree logic
on the mocked Fusion structure from the tests.

    uv run python -m tools.make_demo
"""
import json
import pathlib

from massanalyzer import heat
from massanalyzer.mass_tree import build_tree
from tests.fusion_mocks import Body, Component, Occurrence

screw = Component("Vis M6", [Body("Vis", 0.0042)])
nut = Component("Ecrou M6", [Body("Ecrou", 0.0021)])
motor = Component("Moteur", [Body("Carter", 1.85), Body("Rotor", 0.92)])
wheel = Component("Roue", [Body("Jante", 1.4), Body("Pneu", 0.65)])
hub = Component("Moyeu", [Body("Moyeu", 0.38)])
drive = Component("Module traction", [Body("Support", 0.75)])
arm = Component("Bras", [Body("Tube", 0.52)])
tool = Component("Outil", [Body("Lame", 0.31), Body("Porte-lame", 0.18)])
camera = Component("Camera", [Body("Boitier", 0.12), Body("Capot", 0.0, material=None, solid=False)])
battery = Component("Batterie", [Body("Pack", 6.8)])
cover = Component("Capot", [Body("Toles", 3.1)])


def drive_unit(i):
    return Occurrence(drive, i, children=[
        Occurrence(motor, i), Occurrence(hub, i),
        Occurrence(wheel, i, children=[Occurrence(screw, 4 * i + k) for k in range(4)]),
        Occurrence(nut, i),
    ])


root = Component("Robot desherbeur", bodies=[Body("Chassis", 14.2)], occurrences=[
    *[drive_unit(i) for i in range(1, 5)],
    Occurrence(arm, 1, children=[Occurrence(tool, 1), Occurrence(screw, 30), Occurrence(screw, 31)]),
    Occurrence(arm, 2, children=[Occurrence(tool, 2)]),
    Occurrence(camera, 1), Occurrence(battery, 1), Occurrence(cover, 1),
])

payload = build_tree(root).to_payload()
payload["document"] = "Démo (hors Fusion)"
payload["heatmapActive"] = False
legend = heat.legend()

js = """// Generated by tools/make_demo.py - demo data for previewing the palette outside Fusion.
window.FMA_DEMO = {
  payload: %s,
  legend: %s,
  handle(action, data) {
    switch (action) {
      case "ready": case "analyze": return JSON.parse(JSON.stringify(this.payload));
      case "select": return { selected: true };
      case "heatmap": return { colored: 0, legend: this.legend, heatmapActive: true };
      case "restore": return { restored: 0, heatmapActive: false };
      case "exportCsv": return { cancelled: true };
    }
    return {};
  },
};
""" % (json.dumps(payload, ensure_ascii=False), json.dumps(legend))
out = pathlib.Path(__file__).resolve().parent.parent / "palette" / "demo.js"
out.write_text(js, encoding="utf-8")
print("wrote", out, len(js), "bytes")
